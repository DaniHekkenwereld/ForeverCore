# ForeverCore: offline export of account-wide UI settings from installed addons.
# Called by Export-PortableSnapshot.ps1. No game login is required.
param(
    [Parameter(Mandatory = $true)][string] $GameRoot,
    [Parameter(Mandatory = $true)][string] $Account,
    [string] $AddonRoot
)
$ErrorActionPreference = 'Stop'
if (-not $AddonRoot) { $AddonRoot = Split-Path -Parent $PSScriptRoot }
$addonsPath = Join-Path $GameRoot 'Interface\AddOns'
$savedPath = Join-Path (Join-Path (Join-Path $GameRoot 'WTF\Account') $Account) 'SavedVariables'
if (-not (Test-Path -LiteralPath $savedPath)) { throw "SavedVariables-map ontbreekt: $savedPath" }
if (-not (Test-Path -LiteralPath $addonsPath)) { throw "AddOns-map ontbreekt: $addonsPath" }

# Explicit allowlist. Other addons can mix settings with personal notes,
# quests, character progress, bag scans or combat history.
$included = @(
    'Bagnon', 'Bagnon_Bank', 'Bagnon_Config', 'Bagnon_GuildBank',
    'BetterBlizzFrames', 'GTFO', 'Leatrix_Maps', 'Plater',
    'Scrap', 'TinyTooltip'
)
$excluded = @{
    'ForeverCore' = 'eigen snapshot'
    'Bartender4' = 'eigen Bartender-snapshot'
    'Questie' = 'afzonderlijk Questie-profiel; questvoortgang uitgesloten'
    'Details' = 'afzonderlijk Details-profiel; combatdata uitgesloten'
    'BagBrother' = 'persoonlijke tas- en bankcaches'
    'Details_DataStorage' = 'combatdata'
    'Polestar' = 'guidevoortgang; specifieke adapter nodig'
    'Factoruide_Polestar' = 'guidevoortgang; specifieke adapter nodig'
    'HandyNotes' = 'persoonlijke notities; specifieke adapter nodig'
    'Spoken' = 'luistergeschiedenis; specifieke adapter nodig'
    'ForeverBeastLore' = 'speldata; specifieke adapter nodig'
    'ForeverBugReporter' = 'bugmeldingen; specifieke adapter nodig'
    'ForeverDungeonBuddy' = 'characterdata mogelijk; specifieke adapter nodig'
    'rxp-free-guides-master' = 'guidevoortgang; specifieke adapter nodig'
}
$allowed = @{}
foreach ($addon in $included) { $allowed[$addon.ToLowerInvariant()] = $true }

# Extract a Lua literal without evaluating SavedVariables as code.
function Read-LuaLiteral([string] $src, [int] $idx) {
    while ($idx -lt $src.Length -and [char]::IsWhiteSpace($src[$idx])) { $idx++ }
    if ($idx -ge $src.Length) { return $null }
    if ($src[$idx] -eq '{') {
        $depth = 0
        $quoted = $false
        $escaped = $false
        for ($i = $idx; $i -lt $src.Length; $i++) {
            $ch = $src[$i]
            if ($quoted) {
                if ($escaped) { $escaped = $false; continue }
                if ($ch -eq '\') { $escaped = $true; continue }
                if ($ch -eq '"') { $quoted = $false }
                continue
            }
            if ($ch -eq '"') { $quoted = $true; continue }
            if ($ch -eq '{') { $depth++ }
            if ($ch -eq '}') {
                $depth--
                if ($depth -eq 0) { return $src.Substring($idx, $i - $idx + 1) }
            }
        }
        return $null
    }
    $remaining = $src.Substring($idx)
    $str = [regex]::Match($remaining, '^"(?:\\.|[^"\\])*"')
    if ($str.Success) { return $str.Value }
    $scalar = [regex]::Match($remaining, '^(?:true|false|nil|[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?)\b')
    if ($scalar.Success) { return $scalar.Value }
    return $null
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('-- GENERATED by ForeverCore Export-AddonSettings.ps1.')
$lines.Add('-- Contains selected account UI variables. Review the report before sharing.')
$lines.Add('_G.ForeverCoreBundledAddonSettings = {')
$lines.Add('  version = 2,')
$lines.Add('  addons = {')
$report = [System.Collections.Generic.List[string]]::new()
$exported = 0

foreach ($folder in (Get-ChildItem -LiteralPath $addonsPath -Directory | Sort-Object Name)) {
    $name = $folder.Name
    $vars = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)
    $charVars = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::Ordinal)
    $tocs = @(Get-ChildItem -LiteralPath $folder.FullName -Filter '*.toc' -File -ErrorAction SilentlyContinue)
    foreach ($toc in $tocs) {
        $tocText = Get-Content -LiteralPath $toc.FullName -Raw -ErrorAction SilentlyContinue
        if (-not $tocText) { continue }
        foreach ($line in [regex]::Split($tocText, '\r?\n')) {
            $accountMatch = [regex]::Match($line, '^\s*##\s*SavedVariables\s*:\s*(.+)$', [System.Text.RegularExpressions.RegexOptions]::IgnoreCase)
            $charMatch = [regex]::Match($line, '^\s*##\s*SavedVariablesPerCharacter\s*:\s*(.+)$', [System.Text.RegularExpressions.RegexOptions]::IgnoreCase)
            if ($accountMatch.Success) {
                foreach ($v in ($accountMatch.Groups[1].Value -split ',')) {
                    $v = $v.Trim()
                    if ($v -match '^[a-zA-Z_][a-zA-Z_0-9]*$') { [void] $vars.Add($v) }
                }
            }
            if ($charMatch.Success) {
                foreach ($v in ($charMatch.Groups[1].Value -split ',')) {
                    $v = $v.Trim()
                    if ($v -match '^[a-zA-Z_][a-zA-Z_0-9]*$') { [void] $charVars.Add($v) }
                }
            }
        }
    }
    if ($charVars.Count -gt 0) {
        $report.Add("PER-CHARACTER $name : niet overgenomen ($($charVars -join ', '))")
    }
    $isEnhance = $name.StartsWith('EnhanceQoL', [System.StringComparison]::OrdinalIgnoreCase)
    if (-not $allowed.ContainsKey($name.ToLowerInvariant()) -and -not $isEnhance) {
        if ($excluded.ContainsKey($name)) {
            $report.Add("SKIP $name : $($excluded[$name])")
        } elseif ($vars.Count -gt 0) {
            $report.Add("NEEDS ADAPTER $name : $($vars -join ', ')")
        } else {
            $report.Add("NO CONFIG $name : geen account-SavedVariables")
        }
        continue
    }
    if ($vars.Count -eq 0) {
        $report.Add("NO CONFIG $name : geen account-SavedVariables")
        continue
    }
    $savedFile = Join-Path $savedPath ($name + '.lua')
    if (-not (Test-Path -LiteralPath $savedFile)) {
        $report.Add("NO SAVE $name : SavedVariables-bestand ontbreekt")
        continue
    }
    $raw = Get-Content -LiteralPath $savedFile -Raw
    $entries = [System.Collections.Generic.List[string]]::new()
    foreach ($var in $vars) {
        if ($var -match '(?i)Cache|History|Combat|Character|Quest|Inventory|Session|DataStore|Record|Log') {
            $report.Add("SKIP DATA $name/$var")
            continue
        }
        $pattern = '(?m)^\s*' + [regex]::Escape($var) + '\s*=\s*'
        $match = [regex]::Match($raw, $pattern)
        if (-not $match.Success) {
            $report.Add("NO VARIABLE $name/$var")
            continue
        }
        $literal = Read-LuaLiteral $raw ($match.Index + $match.Length)
        if (-not $literal) {
            $report.Add("SKIP PARSE $name/$var")
            continue
        }
        if ($literal.Length -gt 8000000) {
            $report.Add("SKIP SIZE $name/$var : groter dan 8 MB")
            continue
        }
        $entries.Add('      ["' + $var + '"] = ' + $literal + ',')
        $exported++
    }
    if ($entries.Count -eq 0) {
        $report.Add("NO EXPORT $name")
        continue
    }
    $lines.Add('    ["' + $name + '"] = {')
    foreach ($entry in $entries) { $lines.Add($entry) }
    $lines.Add('    },')
    $report.Add("OK $name : $($entries.Count) variabele(n)")
}

$lines.Add('  },')
$lines.Add('}')
$destination = Join-Path $AddonRoot 'PortableAddonSettings.lua'
$reportFile = Join-Path $AddonRoot 'PortableAddonSettings-report.txt'
[System.IO.File]::WriteAllLines($destination, $lines, [System.Text.UTF8Encoding]::new($false))
[System.IO.File]::WriteAllLines($reportFile, $report, [System.Text.UTF8Encoding]::new($false))
Write-Host "Extra addoninstellingen: $exported variabelen" -ForegroundColor Green
Write-Host "Snapshot: $destination"
Write-Host "Controlelijst: $reportFile"
